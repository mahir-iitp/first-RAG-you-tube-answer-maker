from youtube_transcript_api import YouTubeTranscriptApi



from urllib.parse import urlparse, parse_qs

def extract_video_id():
    url = input("Enter YouTube URL: ")

    parsed_url = urlparse(url)

    if parsed_url.hostname in ["www.youtube.com", "youtube.com", "m.youtube.com"]:
        video_id = parse_qs(parsed_url.query).get("v", [None])[0]

    elif parsed_url.hostname == "youtu.be":
        video_id = parsed_url.path.lstrip("/")

    else:
        video_id = None

    return video_id
video_id = extract_video_id()

#print("Extracted Video ID:", video_id)

#V_id = "X5HH-uAcbio"
api = YouTubeTranscriptApi()
transcript = api.fetch(video_id)

print(transcript)

full_text = ''.join([entry.text for entry in transcript])
print(full_text)

word_count = len(full_text.split())
print(f"Word count: {word_count}")

def chunk_text(text, chunk_size=100, overlap=20):
  word  = text.split()
  chunk = []
  for i in range(0, len(word), chunk_size-overlap):
    chunk.append(' '.join(word[i:i+chunk_size]))
  return chunk
chunks = chunk_text(full_text)
print(chunks)

from sentence_transformers import SentenceTransformer
embadding_model = SentenceTransformer("sentence-transformers/all-MiniLM-L6-v2")
embeddings = embadding_model.encode(chunks)
print(embeddings.shape)

import faiss
import numpy as np
embeddings = np.array(
    embeddings,
    dtype = 'float32'
)
dimension = embeddings.shape[1]
index = faiss.IndexFlatIP(dimension)
index.add(embeddings)
print("total vector:", index.ntotal)

def retrive_context(query, top_k=3):
  query_embedding = embadding_model.encode([query])
  faiss.normalize_L2(query_embedding)
  query_embedding = np.array(
      query_embedding,
      dtype = 'float32'
  )
  scores, indices = index.search(
      query_embedding,
      top_k
  )
  retrieved_chunks = []
  for idk in indices[0]:
    if idk != -1:
      retrieved_chunks.append(chunks[idk])
  return retrieved_chunks

from transformers import AutoModelForSeq2SeqLM, AutoTokenizer

model_name = "google/flan-t5-base"
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForSeq2SeqLM.from_pretrained(model_name)

def generate_answer(question, context_chunks):
    context = "\n\n".join(context_chunks)
    prompt = (
        f"Answer the question using only the text below.\n\n"
        f"Text:\n{context}\n\n"
        f"Question: {question}\n\n"
        f"Answer:"
    )

    inputs = tokenizer(prompt, return_tensors="pt", truncation=True, max_length=1024)
    outputs = model.generate(**inputs, max_new_tokens=150)
    return tokenizer.decode(outputs[0], skip_special_tokens=True)

